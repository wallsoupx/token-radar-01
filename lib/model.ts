// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can still surprise us with: the 40
// watchlist slugs (the floor, never the ceiling) plus every other pre-token protocol below the
// floor that could plausibly launch a token of its own. A protocol is rankable when the snapshot
// records no token for it and it is not a wrapped, staked or bridged product of a token that
// already trades, not an exchange, and not a versioned pool of another protocol — the same
// exclusion rule the watchlist itself uses, applied to the early rows too. Live-token protocols
// are kept apart and shown with the market's own market cap, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category  = median(mcap_usd / tvl_usd) of the live-token protocols in the same category
//               (at least 4 of them, else the global median), clamped to [0.05, 1.5].
//               A category whose tokens the market already values richly against TVL
//               earns a richer multiple; a category the market values thinly earns a thin one.
//   growth    = 1 + clamp(change_7d, -50, 150) / 100 * 0.6
//   maturity  = 0.7 + min(age_days, 1460) / 1460 * 0.5   (age unknown: 365 days)
//               A protocol that has run longer with no token has more pent-up launch value.
//   breadth   = 1 + 0.05 * min(chains - 1, 4)
//               A protocol live on more chains can distribute a token more widely.
//   implied   = max(1, round(tvl_usd * category * growth * maturity * breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// recomputes each row from the same figures so the page and board.json visibly agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

